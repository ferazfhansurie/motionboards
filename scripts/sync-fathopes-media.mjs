// Sync FatHopes footage into public/ and regenerate the gallery manifest.
//
// Re-run this any time you add/delete files in fathopes-footages/:
//   node scripts/sync-fathopes-media.mjs
//
// It scans the de-wrapped "FatHopes Energy Brand" source folder, copies every
// viewable media file into public/fathopes/<category>/, and writes the typed
// manifest the /fathopes page reads. Logos/fonts/PDFs/AI files are skipped.

import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "fathopes-footages", "FatHopes Energy Brand");
const PUBLIC_DEST = path.join(ROOT, "public", "fathopes");
const MANIFEST = path.join(ROOT, "src", "lib", "fathopes-media.ts");

const IMAGE_EXT = new Set([".jpg", ".jpeg", ".png", ".webp", ".gif"]);
const VIDEO_EXT = new Set([".mov", ".mp4", ".m4v", ".webm"]);
// Folders we never want in the gallery (vector sources, fonts, raw brand kits).
const SKIP_DIRS = new Set(["02_Typeface"]);

// Order categories sensibly; anything not listed falls to the end, alphabetically.
const CATEGORY_ORDER = [
  "Super Hero", "Images", "Strand Mall", "Wisma CIMB Bangsar 2025",
  "Ranger Training", "Team Building", "Waste2Energy", "Astro",
  "PLUS Community Day", "Mitsui X FatHopes Energy", "KLB Fuel",
  "My Aero 2026", "Turiya Earth Day 2026", "FatHopes Loyalty App",
  "Bunting", "Corporate Asset", "Brand Video", "AI Video",
  "FatHopes Vendor App",
];

function slug(s) {
  return s
    .toLowerCase()
    .replace(/\.[^.]+$/, "")           // drop extension
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "") || "item";
}

function cleanLabel(folder) {
  return folder.replace(/^\d+[_\s]+/, "").trim();
}

async function walk(dir) {
  const out = [];
  let entries;
  try {
    entries = await fs.readdir(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const e of entries) {
    if (e.name.startsWith(".")) continue;
    const full = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (SKIP_DIRS.has(e.name)) continue;
      out.push(...(await walk(full)));
    } else {
      out.push(full);
    }
  }
  return out;
}

function categoryFor(relParts) {
  // 08_Vinesh holds one sub-folder per event — use that as the category.
  if (relParts[0] === "08_Vinesh" && relParts.length > 1) return cleanLabel(relParts[1]);
  return cleanLabel(relParts[0]);
}

async function main() {
  await fs.rm(PUBLIC_DEST, { recursive: true, force: true });

  const files = await walk(SRC);
  const items = [];
  const usedNames = new Map(); // per-category collision guard

  for (const full of files) {
    const ext = path.extname(full).toLowerCase();
    const isImage = IMAGE_EXT.has(ext);
    const isVideo = VIDEO_EXT.has(ext);
    if (!isImage && !isVideo) continue;

    const rel = path.relative(SRC, full).split(path.sep);
    const category = categoryFor(rel);
    const catSlug = slug(category);

    let base = slug(path.basename(full));
    const key = `${catSlug}/${base}`;
    const n = (usedNames.get(key) || 0) + 1;
    usedNames.set(key, n);
    if (n > 1) base = `${base}-${n}`;
    const outName = `${base}${ext}`;

    const destDir = path.join(PUBLIC_DEST, catSlug);
    await fs.mkdir(destDir, { recursive: true });
    await fs.copyFile(full, path.join(destDir, outName));

    items.push({
      src: `/fathopes/${catSlug}/${outName}`,
      category,
      catSlug,
      type: isVideo ? "video" : "image",
      png: ext === ".png",
      name: path.basename(full),
    });
  }

  // Build ordered category list with counts.
  const counts = new Map();
  for (const it of items) {
    if (!counts.has(it.catSlug)) counts.set(it.catSlug, { label: it.category, slug: it.catSlug, count: 0 });
    counts.get(it.catSlug).count++;
  }
  const categories = Array.from(counts.values()).sort((a, b) => {
    const ia = CATEGORY_ORDER.indexOf(a.label);
    const ib = CATEGORY_ORDER.indexOf(b.label);
    if (ia !== -1 || ib !== -1) return (ia === -1 ? 999 : ia) - (ib === -1 ? 999 : ib);
    return a.label.localeCompare(b.label);
  });

  // Order items to follow category order, stable within a category.
  const catRank = new Map(categories.map((c, i) => [c.slug, i]));
  items.sort((a, b) => (catRank.get(a.catSlug) - catRank.get(b.catSlug)) || a.name.localeCompare(b.name));

  const body =
`// AUTO-GENERATED by scripts/sync-fathopes-media.mjs — do not edit by hand.
// Re-run: node scripts/sync-fathopes-media.mjs

export interface FathopesMediaItem {
  src: string;
  category: string;
  catSlug: string;
  type: "image" | "video";
  png: boolean;
  name: string;
}

export interface FathopesCategory {
  label: string;
  slug: string;
  count: number;
}

export const FATHOPES_TOTAL = ${items.length};

export const FATHOPES_CATEGORIES: FathopesCategory[] = ${JSON.stringify(categories, null, 2)};

export const FATHOPES_MEDIA: FathopesMediaItem[] = ${JSON.stringify(items, null, 2)};
`;

  await fs.mkdir(path.dirname(MANIFEST), { recursive: true });
  await fs.writeFile(MANIFEST, body, "utf8");

  console.log(`Copied ${items.length} files across ${categories.length} categories.`);
  for (const c of categories) console.log(`  ${c.label.padEnd(28)} ${c.count}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
